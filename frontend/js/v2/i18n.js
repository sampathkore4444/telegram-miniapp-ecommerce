// Lightweight i18n for the buyer-facing Mini App UI.
// Language is auto-detected from Telegram (language_code), with a
// localStorage override ("st-lang") and a manual switcher in the profile.

export const LANGS = ["en", "id", "vi", "pt"];

export const LANG_META = {
  en: { label: "English", flag: "🇺🇸", locale: "en-US" },
  id: { label: "Bahasa Indonesia", flag: "🇮🇩", locale: "id-ID" },
  vi: { label: "Tiếng Việt", flag: "🇻🇳", locale: "vi-VN" },
  pt: { label: "Português", flag: "🇧🇷", locale: "pt-BR" },
};

const STORAGE_KEY = "st-lang";

function telegramLangCode() {
  try {
    return window.Telegram?.WebApp?.initDataUnsafe?.user?.language_code || "";
  } catch {
    return "";
  }
}

function detectLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch { /* storage unavailable */ }
  let code = "en";
  try {
    code = (telegramLangCode() || navigator.language || "en").toLowerCase();
  } catch { /* navigator unavailable */ }
  for (const l of LANGS) {
    if (code === l || code.startsWith(`${l}-`)) return l;
  }
  if (code.startsWith("in")) return "id";
  return "en";
}

let current = detectLang();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!LANGS.includes(lang)) lang = "en";
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  try {
    if (document.documentElement) document.documentElement.lang = LANG_META[lang].locale.split("-")[0];
  } catch { /* no document */ }
  try { window.dispatchEvent(new CustomEvent("langchange", { detail: lang })); } catch { /* no window */ }
}

export function t(key, vars) {
  let str = (DICTS[current] && DICTS[current][key]) ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

